#!/usr/bin/env python3
"""Generate the solved walkthrough notebooks from the exercise notebooks.

A walkthrough notebook is the attendee notebook with its clone cell pointed at
that part's solution branch, so every cell runs green from the top with no
editing. That is the notebook to drive live, next to the deck: the slides carry
the narration, this carries the execution.

    python3 presentation/generate_walkthrough.py

Nothing here is edited by hand -- re-run the script instead.
"""

import json
import re
import sys
import uuid
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
HERE = REPO / "presentation"

PARTS = [
    ("session1/session1_part1_cpu.ipynb", "session1-part1-solution"),
    ("session1/session1_part2_gpu.ipynb", "session1-part2-solution"),
    ("session2/session2_part1_cpu.ipynb", "session2-part1-solution"),
    ("session2/session2_part2_gpu.ipynb", "session2-part2-solution"),
]


def markdown_cell(source):
    return {"cell_type": "markdown", "id": uuid.uuid4().hex[:12],
            "metadata": {}, "source": source.splitlines(keepends=True)}


def use_solution_branch(notebook, branch):
    """Point the clone cell at `branch`. The exercise notebooks either clone
    the default branch (session 1 part 1, session 2) or already clone a
    solution branch (session 1 part 2, whose exercises start from part 1)."""
    for cell in notebook["cells"]:
        if cell["cell_type"] != "code":
            continue
        source = "".join(cell["source"])
        if "git clone" not in source:
            continue

        if "--branch" in source:
            patched = re.sub(r'^(\s*\w+_BRANCH = )".*"$', rf'\1"{branch}"',
                             source, count=1, flags=re.M)
        else:
            patched = source.replace(
                "    !git clone ",
                f'    WALKTHROUGH_BRANCH = "{branch}"\n    !git clone ', 1)
            patched = patched.replace(
                "--no-single-branch https://",
                "--no-single-branch --branch {WALKTHROUGH_BRANCH} https://", 1)
        if patched == source:
            sys.exit("could not point the clone cell at the solution branch")
        cell["source"] = patched.splitlines(keepends=True)
        return
    sys.exit("no clone cell found")


for notebook_path, branch in PARTS:
    source = REPO / notebook_path
    if not source.exists():
        print(f"{notebook_path}: missing, skipped")
        continue

    notebook = json.loads(source.read_text())
    use_solution_branch(notebook, branch)
    notebook["cells"].insert(0, markdown_cell(
        f"# Presenter walkthrough — `{source.name}`\n"
        f"\n"
        f"**Solved copy, for driving the session live.** It clones the "
        f"`{branch}` branch, so every cell below runs as-is with no editing; "
        f"attendees run the exercise notebook, which does not. The narration "
        f"lives in the deck, `presentation/{source.stem.split('_cpu')[0].split('_gpu')[0]}.pdf`.\n"
        f"\n"
        f"Generated by `presentation/generate_walkthrough.py` — do not edit "
        f"this notebook; re-run the script.\n"))

    destination = HERE / (source.stem.replace("_cpu", "").replace("_gpu", "")
                          + "_walkthrough.ipynb")
    notebook["metadata"].setdefault("colab", {})["name"] = destination.name
    destination.write_text(json.dumps(notebook, indent=1) + "\n")
    print(f"wrote {destination.relative_to(REPO)} ({len(notebook['cells'])} cells)")
